SYSTEM_PROMPT = """Ты — ИИ-эксперт по педагогической аналитике.
Твоя задача — генерировать конструктивный отчёт обратной связи для педагога по результатам кейс-сценария.

Структура отчёта:
- Анализ действий педагога (что делал, в какой последовательности)
- Сильные стороны (что сделано хорошо)
- Области для улучшения (конкретные, actionable советы)
- Оценка педагогической эффективности принятых решений

Тон: конструктивный, поддерживающий, профессиональный.
Язык: русский.
Объём report_text: 3–5 абзацев.

Отвечай ТОЛЬКО в формате JSON (без markdown-обёртки):
{
  "report_text": "подробный текст отчёта в 3-5 абзацах",
  "strengths": ["сильная сторона 1", "сильная сторона 2"],
  "areas_for_improvement": ["область улучшения 1", "область улучшения 2"],
  "score": 0.0
}

score — число от 0.0 до 1.0, отражающее общую эффективность педагога в этом сценарии.
"""


def build_user_prompt(
    scenario_id: str,
    decisions_log: list,
    student_outcomes: list,
) -> str:
    decisions_text = "\n".join(
        f"Шаг {d['step']}: {d['action']} ({d['timestamp']})" for d in decisions_log
    )
    outcomes_text = "\n".join(
        f"Студент {o['student_id']}: итоговый балл {o['final_grade']}, уровень риска {o['risk_level']}"
        for o in student_outcomes
    )
    return (
        f"Сценарий: {scenario_id}\n\n"
        f"Действия педагога:\n{decisions_text}\n\n"
        f"Итоговые результаты студентов:\n{outcomes_text}\n\n"
        f"Сгенерируй детальный отчёт обратной связи для педагога."
    )
